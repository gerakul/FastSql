using System;
using System.Linq;
using AwesomeAssertions;
using Gerakul.FastSql.Common;
using Gerakul.FastSql.IntegrationTests.Common;
using Gerakul.FastSql.IntegrationTests.Infrastructure;
using Npgsql;
using Xunit;

namespace Gerakul.FastSql.IntegrationTests.PostgreSQL
{
    // P2 (phase 5): CreateInsertAndGetID on PostgreSQL: "with inserted as (insert ... returning *)" and the row's value of
    // its serial or identity column, which a catalog lookup finds. The scenarios of both providers are in
    // Common/InsertAndGetIdTests; here what is PostgreSQL's own: bigint, explicit values, triggers, names
    [Trait("Provider", "PostgreSQL")]
    public class PostgreSqlInsertAndGetIdTests : InsertAndGetIdTests<PostgreSqlDatabase>
    {
        public PostgreSqlInsertAndGetIdTests(PostgreSqlDatabase database)
            : base(database)
        {
        }

        protected override string IdentityColumnType => "int generated always as identity";

        protected override Type ServerExceptionType => typeof(PostgresException);

        [Theory]
        [MemberData(nameof(ContextKinds.All), MemberType = typeof(ContextKinds))]
        public void CreateInsertAndGetID_ExecuteScalar_ReturnsIdentityAsBigint(ContextKind kind)
        {
            var table = CreatePersonTableWithIdentity();

            var id = Database.Run(kind, x => x.CreateInsertAndGetID(table, new { GroupID = 1, Name = "Alice", Age = 30 }).ExecuteScalar());

            id.Should().BeOfType<long>().Which.Should().Be(1L);
        }

        [Fact]
        public void CreateInsertAndGetID_IdentityAlwaysNotIgnored_ThrowsServerError()
        {
            var table = CreatePersonTableWithIdentity();
            var person = new Person() { ID = 100, GroupID = 1, Name = "Alice", Age = 30 };

            ShouldThrowServerError(() => Database.Run(ContextKind.ConnectionString, x => x.CreateInsertAndGetID(table, person).ExecuteScalar()),
                "428C9: cannot insert a non-DEFAULT value into column \"ID\"*");
        }

        // a serial or "by default" identity column takes an explicit value, which comes back as given (scope_identity()
        // returns the explicit value of an insert with identity_insert on, too)
        [Theory]
        [InlineData("serial")]
        [InlineData("bigint generated by default as identity")]
        public void CreateInsertAndGetID_ExplicitValueIntoColumnThatTakesIt_ReturnsThatValue(string columnType)
        {
            var table = Database.CreateScratchTable($"{Q("ID")} {columnType} primary key, {Q("GroupID")} int not null, {Q("Name")} varchar(50) null, {Q("Age")} int null");

            var ids = Database.Run(ContextKind.Connection, x => new[]
            {
                x.CreateInsertAndGetID(table, new Person() { ID = 100, GroupID = 1 }).ExecuteScalar<long>(),
                x.CreateInsertAndGetID(table, new Person() { GroupID = 2 }, "ID").ExecuteScalar<long>()
            });

            ids.Should().Equal(100L, 1L);
        }

        // the ID is the inserted row's own value: a trigger that inserts into a table with another sequence does not change
        // it (lastval() would return the other table's value)
        [Fact]
        public void CreateInsertAndGetID_TriggerInsertsIntoAnotherTable_ReturnsOwnId()
        {
            var table = CreatePersonTableWithIdentity();
            var log = Database.CreateScratchTable("id serial primary key, person_id int not null");
            Database.Execute($"insert into {log} (person_id) select g from generate_series(1, 50) g; "
                + $"create function {table}_log() returns trigger language plpgsql as $$ begin insert into {log} (person_id) values (new.{Q("ID")}); return new; end $$; "
                + $"create trigger {table}_log after insert on {table} for each row execute function {table}_log();");

            var ids = Database.Run(ContextKind.Connection, x => new[]
            {
                x.CreateInsertAndGetID(table, new { GroupID = 1, Name = "Alice" }).ExecuteScalar<long>(),
                x.CreateInsertAndGetID(table, new { GroupID = 2, Name = "Bob" }).ExecuteScalar<long>()
            });

            ids.Should().Equal(1L, 2L);
            Database.Run(ContextKind.ConnectionString, x => x.CreateSimple($"select max(id) from {log}").ExecuteScalar<long>()).Should().Be(52L);
        }

        // the table name is the text the caller passes, in the insert and in the catalog lookup
        [Fact]
        public void CreateInsertAndGetID_QuotedAndSchemaQualifiedNames_ReturnsGeneratedIds()
        {
            var schema = "parity_" + Guid.NewGuid().ToString("N").Substring(0, 8);
            Database.Execute($"create schema {schema}; create table {schema}.\"Mixed Case\" (\"Id\" serial primary key, \"Name\" varchar(50) null)");
            var table = $"{schema}.\"Mixed Case\"";

            var ids = Database.Run(ContextKind.ConnectionString, x => new[]
            {
                x.CreateInsertAndGetID(table, new { Name = "Alice" }).ExecuteScalar<long>(),
                x.CreateInsertAndGetID(table, new { Name = "Bob" }).ExecuteScalar<long>()
            });

            ids.Should().Equal(1L, 2L);
        }

        // the statement is a select, so the driver reports no rows affected; SQL Server reports the insert's 1
        [Fact]
        public void CreateInsertAndGetID_ExecuteNonQuery_ReturnsMinusOneAndInserts()
        {
            var table = CreatePersonTableWithIdentity();

            var affected = Database.Run(ContextKind.ConnectionString, x => x.CreateInsertAndGetID(table, new { GroupID = 1, Name = "Alice" }).ExecuteNonQuery());

            affected.Should().Be(-1);
            ReadPersons(table).Should().HaveCount(1);
        }
    }
}
